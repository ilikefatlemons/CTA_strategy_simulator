计算周期: tuple[str, ...] = ("1m", "5m", "15m", "30m", "2h", "1d")

# 出场理由。**只有两种** —— 无部分止盈, 无时段末强平。
#
# 刻意**不叫「止盈」**: 吊灯结构上是一条追踪止损, 它完全可以在亏损处成交。
# 几何见模块 docstring「吊灯为什么会亏着出场」一节 —— 这不是 bug, 是这套装配
# 自带的性质, 面板必须把吊灯出场的盈/亏分开报。
止损 = "SL"          # 固定止损被打掉 (入场价 ∓ 1.5 ATR₀)
吊灯 = "TRAIL"       # 追踪线被打掉 (持仓极值 ∓ 3 ATR₀)
出场理由 = (止损, 吊灯)


# ------------------------------------------------------------ 数据结构 ----
@dataclass
class _持仓:
    方向: int                    # +1 / -1
    入场下标: int
    入场价: float
    入场ATR: float               # 入场那一刻的 30m ATR(14), **冻结**
    固定止损位: float            # 入场时冻结, 此后不变
    持仓极值: float
    吊灯位: float = float("nan")


@dataclass(frozen=True)
class 一笔:
    方向: str                    # "多" | "空"
    入场下标: int
    入场时间: pd.Timestamp
    入场价: float                # = 开盘价[入场下标], 实际成交价
    出场下标: int
    出场时间: pd.Timestamp
    出场价: float
    理由: str                    # SL (固定止损) | TRAIL (吊灯, 可盈可亏)
    仓位比例: float              # 恒为 1.0 —— 本策略无部分止盈
    跳空成交: bool               # True = 按 bar 的 open 成交, 不是按线
    固定止损位: float            # 审计/展示用
    交易日: pd.Timestamp
    时段号: int
    成本基点: float

    @property
    def 毛收益(self) -> float:
        动 = (self.出场价 - self.入场价) if self.方向 == "多" \
            else (self.入场价 - self.出场价)
        return 动 / self.入场价

    @property
    def 净收益(self) -> float:
        """往返成本每批收一次。本策略一批一腿, 所以就是每笔一次。"""
        return self.毛收益 - self.成本基点 / 1e4

    @property
    def 持有根数(self) -> int:
        return self.出场下标 - self.入场下标


@dataclass
class 回测结果:
    品种: str
    交易: list[一笔]
    # 权益曲线与交易日只含**显示窗口**(暖机段被切掉), 起点归 1.0
    权益曲线: pd.Series
    交易日: pd.Series
    # 逐根, **全帧**(含暖机段): 图层要按 bin 分箱, 用全帧下标最省心
    仓位: np.ndarray             # int8: -1 / 0 / +1
    # 逐根三条线, 空仓一律 NaN。恒等式: 止损线 = max(固定止损线, 吊灯原线) (空头取 min),
    # 由 `tests/test_lineA_03_backtest.py::test_三条止损线满足取大取小的恒等式` 钉死。
    止损线: np.ndarray           # float64: 该根**被测试**的有效止损位
    固定止损线: np.ndarray       # float64: 入场时冻结, 整笔恒定
    吊灯原线: np.ndarray         # float64: 极值 ∓ 3·ATR₀, **不带地板** —— 所以它在浮盈
                                 #          涨过 +1R 之前会坐在固定止损的更差一侧。
                                 #          图层要画出这一段, 才看得见两条线什么时候交叉。
    吊灯受阻: np.ndarray         # bool: 本根吊灯线差于入场价, 被止盈阀门挡住 ——
                                 #       有效止损退回固定止损。图层据此换色。
    可成交: np.ndarray           # bool: 本根的价格可成交 (竞价根不可)。出场与极值折入
                                 #       都受它挡; 竞价根上三条止损线都不写。
    # 以下全部**仅观测**, 没有任何决策读它们。图上的标注开关用。
    回调闩锁点: list             # {"下标", "方向"}
    大周期翻转点: list           # {"下标", "方向"}
    开关1点: list              # {"下标", "方向"}
    开关2点: list              # {"下标", "方向"}
    冷静期区间: list             # [(起下标, 止下标)] 闭区间
    暖机根数: int
    暖机天数: int
    可交易日: int
    末尾未平仓: int              # 数据末尾仍持仓的批数。**刻意丢弃, 但如实报出**
    参数: 策略参数
    开关: 策略开关
    时段模式: str
    丢弃段: pd.DataFrame = field(default_factory=pd.DataFrame)

    @property
    def 持仓中(self) -> np.ndarray:
        return ~np.isnan(self.止损线)


# ---------------------------------------------------------------- 引擎 ----
def 跑回测(
    prepared: Prepared,
    tf: dict[str, TFBars] | None = None,
    参数: 策略参数 | None = None,
    开关: 策略开关 | None = None,
) -> 回测结果:
    """
    `tf` 作为参数而不是内部构造, 是为了让测试能喂一个等构的合成结构进来 ——
    与 `pullback_v3_backtest.run_pullback_v3_backtest` 同一个理由。
    """
    p = 参数 or 策略参数()
    cfg = 开关 or 策略开关()
    df = prepared.df
    if len(df) == 0:
        return _空结果(prepared, p, cfg)
    if tf is None:
        tf = build_timeframes(df, tfs=计算周期)

    # ---------------------------------------------------------- 预计算 ----
    大 = tf[p.大周期]          # 2h  方向 + 冷静期
    回 = tf[p.回调周期]        # 15m 回调判定 + 两个开关 (**信号层**, 不是时钟)
    险 = tf[p.风险周期]        # 30m 只出一个 ATR₀, 不参与任何时序判定
    钟 = tf[p.驱动周期]        # **驱动时钟** —— 成交、出场触发、极值、MTM 都在它上面

    n = 钟.n_bars
    if n == 0:
        return _空结果(prepared, p, cfg)

    大周期 = 大周期状态(大.bars["close"].to_numpy("float64"), p.快线, p.慢线)
    回调侧 = 三线状态(回.bars["close"].to_numpy("float64"), p.快线, p.慢线)
    大周期_生 = 三线状态(大.bars["close"].to_numpy("float64"), p.快线, p.慢线)

    回收 = 回.bars["close"].to_numpy("float64")
    回MA快 = np.asarray(pd.Series(回收).rolling(p.快线).mean(), dtype="float64")
    dif, dea = macd线(回收, p.MACD快, p.MACD慢, p.MACD信号)
    开关2多, 开关2空 = 动量开关(dif, dea, p.MACD最少根数)

    ATR险 = np.asarray(atr_series(险.bars, p.ATR周期), dtype="float64")

    # 每根驱动 bar 的首个 1m 成分下标。**只用来把 1m 层的窗口形状旗标、以及各周期的
    # `closed_pos` 折算到驱动周期上**, 一个价格都不从这里取。
    # 驱动周期就是 1m 时它退化成 arange, 下面所有 `[首]` 取样都成了恒等。
    首 = np.flatnonzero(np.r_[True, 钟.bin_of[1:] != 钟.bin_of[:-1]])

    # 「截至驱动 bar i **开盘那一刻**, 各周期最后一根已收盘 bar 是哪根」。
    # 驱动 bar i 的开盘时刻 == 它首个 1m 成分的开盘时刻, 所以直接取 1m 层算好的
    # `closed_pos` 在 `首[i]` 处的值 —— 语义逐位等同, 不必另算一遍。
    c大 = 大.closed_pos[首].astype(np.int64)
    c险 = 险.closed_pos[首].astype(np.int64)
    c回 = 回.closed_pos[首].astype(np.int64)
    c钟 = 钟.closed_pos[首].astype(np.int64)
    # **驱动时钟因果性的机械凭据**: 驱动周期自己的「已收盘」必须恒等于 i-1。
    # 破了这条, 「只用 bar i-1 及更早」就无从谈起。
    if not np.array_equal(c钟, np.arange(n, dtype=np.int64) - 1):
        raise ValueError(
            f"{p.驱动周期} 的 closed_pos 不恒等于 i-1 —— 驱动时钟的因果性破了")

    # 价格一律取自**驱动周期自己的 bar**。
    op = 钟.bars["open"].to_numpy("float64")
    hi = 钟.bars["high"].to_numpy("float64")
    lo = 钟.bars["low"].to_numpy("float64")
    cl = 钟.bars["close"].to_numpy("float64")
    时刻 = 钟.bars.index.to_numpy()
    交易日列 = 钟.bars["trading_date"].to_numpy()
    # 箱不跨原子段, 段不跨 trading_date, 所以整箱同一个 session_id, 取首根即可。
    时段号列 = df["session_id"].to_numpy("int64")[首]

    # ------------------------------------------------------------ 闸门 ----
    # **挡的是集合竞价撮合根, 不是「时段首根」。** 两者不是一回事:
    #
    #   竞价根        AU 268 根, 全在 21:00, 零振幅 100%, 成交中位 99 手
    #                 —— 一个撮合价, 没有连续交易, 按这个价成交是假的
    #   只是段首根    AU 另有 274 根 09:01, 零振幅 0%, 成交中位 2266 手
    #                 —— 白盘第一分钟, 是**真实可交易**的
    #
    # 判据见 `v3_timeframes._竞价根`: 段首根且与下一根落在不同的 30 分钟时钟格。
    # 它的 docstring 已经写明「AU 的白盘数据里确实没有竞价根, 夜盘 21:00 才有」。
    # 之前用 `is_session_first` 当闸门, 把那 274 根白盘首分钟一起挡了 —— 那是错的。
    竞价 = _竞价根(df, derive_segments(df))

    # 折到驱动周期。**驱动周期就是 1m 时这三行全是恒等**, 折叠这件事本身只是粗时钟
    # 的产物: 一根 15m 要么整根能开仓要么整根不能, 没有中间态可表达。
    可交易 = np.logical_and.reduceat(df["tradable"].to_numpy(bool), 首)
    在窗口 = np.logical_and.reduceat(np.asarray(prepared.in_window, dtype=bool), 首)
    含竞价 = np.logical_or.reduceat(竞价, 首)
    # 入场闸门: 窗口形状属性, 与价格无关。
    可入场 = 可交易 & 在窗口 & ~含竞价
    # **竞价根的价格不可成交, 所以凡是「会导致按这个价成交、或因这个价而改变成交」
    # 的地方一律排除**: 入场 (上面的闸门)、出场、以及**极值折入**。
    #
    # 极值那条最容易漏: 竞价根是零振幅的单点, 折进持仓极值会把吊灯线拉走, 进而改变
    # 真实出场 —— 实测 AU 上 91 个落在持仓区间内的竞价根里, 有 24 个 (26%) 真的刷新
    # 了极值, 最大一次把极值推了 4.95。那是拿一个不可成交的撮合价去移动一条真实的
    # 止损线。
    #
    # 逐根 mark-to-market **不在此列**: 它只记账、不产生成交, 而竞价价是那一刻交易所
    # 公布的唯一价格, 按它记账是诚实的。
    可成交 = ~含竞价

    # ------------------------------------------------------------ 状态 ----
    批: _持仓 | None = None
    方向 = 未定
    已武装 = False
    冻结中 = False
    连续止损 = 0
    上次止损方向 = 0
    上一根大周期下标 = -1
    稳定态, 稳定计数 = 未定, 0

    交易: list[一笔] = []
    资金 = 1.0
    权益 = np.ones(n, dtype="float64")
    仓位 = np.zeros(n, dtype=np.int8)
    止损线 = np.full(n, np.nan, dtype="float64")
    固定止损线 = np.full(n, np.nan, dtype="float64")
    吊灯原线 = np.full(n, np.nan, dtype="float64")
    吊灯受阻 = np.zeros(n, dtype=bool)

    回调闩锁点: list = []
    大周期翻转点: list = []
    开关1点: list = []
    开关2点: list = []
    冷静期区间: list = []
    冷起 = None
    上次开关1 = False
    上次开关2 = False

    # ------------------------------------------------------------ 主循环 ----
    for i in range(n):
        D, R, X = int(c大[i]), int(c回[i]), int(c险[i])

        # -------------------------------------------- 1) 冷静期 (2h 门控) ----
        # 每根**新 2h** 才评一次。不门控的话「连续三根」会按调用次数推进
        # (3 根 1m = 3 分钟而不是 3 根 2h), 冷静期形同虚设。
        # goal.md: 「止损的当前根不能计入 count，一定从止损过的当根 2h bar 的下一根
        # 开始算」—— 冻结那一刻把 上一根大周期下标 钉在当时的 D 上, 于是同一根 2h
        # 不会被计入, 计数从下一根新 2h 才开始。
        if D >= 0 and D != 上一根大周期下标:
            上一根大周期下标 = D
            if 冻结中:
                s = 大周期_生[D]
                if s == 未定 or s != 稳定态:
                    稳定态 = s
                    稳定计数 = 1 if s != 未定 else 0
                else:
                    稳定计数 += 1
                if s != 未定 and 稳定计数 >= p.冷静期_解冻根数:
                    冻结中 = False
                    稳定态, 稳定计数 = 未定, 0
                    连续止损, 上次止损方向 = 0, 0

        # ---------------------------------------------- 2) 大周期方向 ----
        if D >= 0:
            新方向 = 大周期[D]
            if 新方向 != 方向:
                if 方向 != 未定 and 新方向 != 未定:
                    大周期翻转点.append({"下标": i, "方向": int(新方向)})
                # 大周期翻转是唯一的全量重置点 —— 清回调武装与入场状态, **但不平仓**
                方向, 已武装 = 新方向, False
                上次开关1 = 上次开关2 = False

        # ------------------------------------- 3~6) 入场 (排在出场之前) ----
        if 批 is None:
            批, 已武装, 上次开关1, 上次开关2 = _尝试入场(
                i, D, R, 方向, 已武装, 冻结中, 回调侧, 回MA快, 回收,
                开关2多, 开关2空, 可入场, op, ATR险, X, p, cfg,
                回调闩锁点, 开关1点, 开关2点, 上次开关1, 上次开关2,
            )

        # -------------------------------------------------- 7~10) 出场 ----
        # `一根bar只做一个动作` 开着时守卫是 `<` —— 本根开的仓本根不测出场。
        # 同根既开又平要求知道 bar 内部「先到开盘价还是先到止损位」的次序, 而这一
        # 版的立场恰恰是**不知道**。15m 时代实测 100 笔里有 1 笔是同根开平的。
        if 批 is not None and 可成交[i] and (批.入场下标 < i if cfg.一根bar只做一个动作
                                            else 批.入场下标 <= i):
            是多 = 批.方向 == 多
            bo, bh, bl = op[i], hi[i], lo[i]

            # 吊灯用的 ATR: 由 `开关.止盈_ATR随动` 决定 (二稿 L56)。
            #
            # 随动时取的是 `c险[i]` 那一根 —— 「截至本根、最后一根**已收盘**的 30m」,
            # **不是包含本根的那一根**。后者成交时还没收盘, 用它就是未来函数。
            #
            # 代价: 追踪线不再单调, ATR 上升而极值不变时会**后退**。刻意接受。
            if not cfg.止盈_ATR随动 or X < 0 or np.isnan(ATR险[X]):
                吊ATR = 批.入场ATR
            else:
                吊ATR = float(ATR险[X])
            原线 = (批.持仓极值 - p.吊灯ATR倍数 * 吊ATR if 是多
                    else 批.持仓极值 + p.吊灯ATR倍数 * 吊ATR)
            # 止盈阀门: 吊灯线差于入场价时本根不许用它出场, 退回固定止损。
            受阻 = cfg.止盈_不得差于入场价 and (
                原线 < 批.入场价 if 是多 else 原线 > 批.入场价)
            if 受阻:
                批.吊灯位 = 批.固定止损位
            else:
                批.吊灯位 = (max(原线, 批.固定止损位) if 是多
                            else min(原线, 批.固定止损位))
            吊灯受阻[i] = 受阻
            有效线 = 批.吊灯位
            止损线[i] = 有效线
            # 不带地板的原始吊灯 —— 只做记录, **不参与任何判定**。图层拿它画出
            # 「吊灯还压在固定止损下方」的那一段。
            固定止损线[i] = 批.固定止损位
            吊灯原线[i] = 原线

            命中 = (bl <= 有效线) if 是多 else (bh >= 有效线)
            if 命中:
                成交 = gap_filled(有效线, 是多, bo, True)
                # 出场理由二分: 有效线还等于固定止损 -> SL; 吊灯已抬起来 -> TP
                理由 = 止损 if 有效线 == 批.固定止损位 else 吊灯
                交易.append(_成腿(批, i, 成交, 理由, 时刻, 交易日列, 时段号列, cfg,
                                跳空=成交 != 有效线))
                资金 *= 1.0 + 交易[-1].净收益
                if 理由 == 止损:
                    连续止损, 上次止损方向 = _计止损(
                        连续止损, 上次止损方向, 批.方向, cfg)
                    if 连续止损 >= p.冷静期_止损次数:
                        冻结中 = True
                        连续止损, 上次止损方向 = 0, 0
                        稳定态, 稳定计数 = 未定, 0
                        # goal.md: 止损那根 2h 不计数, 从下一根起算
                        上一根大周期下标 = D
                else:
                    连续止损, 上次止损方向 = 0, 0
                批 = None

        # ------------------------------------------------ 11) 极值折入 ----
        # 本根 high/low 只在出场**测试之后**折入, 所以拿去和本根比较的那条线永远
        # 不依赖本根。带守卫 —— 上面可能刚把这一批平掉。
        if 批 is not None and 可成交[i] and 批.入场下标 <= i:
            批.持仓极值 = (max(批.持仓极值, hi[i]) if 批.方向 == 多
                          else min(批.持仓极值, lo[i]))

        # ------------------------------------ 12) 逐根 mark-to-market ----
        浮盈 = 0.0
        if 批 is not None and 批.入场下标 <= i:
            仓位[i] = np.int8(批.方向)
            动 = (cl[i] - 批.入场价) if 批.方向 == 多 else (批.入场价 - cl[i])
            浮盈 = 动 / 批.入场价 - cfg.成本_每笔基点 / 1e4
        权益[i] = 资金 * (1.0 + 浮盈)

        # ------------------------------------ 13) 冷静期区间 (仅观测) ----
        if 冻结中:
            if 冷起 is None:
                冷起 = i
        elif 冷起 is not None:
            冷静期区间.append((冷起, i - 1))
            冷起 = None

    if 冷起 is not None:
        冷静期区间.append((冷起, n - 1))

    # 数据末尾仍持仓: **刻意丢弃**, 不造合成腿 —— 少一笔数据好过多一笔错误数据。
    # 但要如实报出批数, 让它是可见的丢弃而不是静默的丢弃。
    末尾未平仓 = 1 if 批 is not None else 0

    # 暖机段按 15m 根数切。切点是 trading_date 边界, 而 15m 箱不跨 trading_date,
    # 所以边界处不会出现半根被切开的箱。
    w = 钟.first_bin_at_or_after(prepared.warmup_bars)
    idx = pd.DatetimeIndex(时刻[w:], name="datetime")
    eq = pd.Series(权益[w:], index=idx)
    eq = eq / eq.iloc[0] if len(eq) else eq
    return 回测结果(
        品种=prepared.symbol, 交易=交易,
        权益曲线=eq,
        交易日=pd.Series(交易日列[w:], index=idx),
        仓位=仓位, 止损线=止损线, 固定止损线=固定止损线, 吊灯原线=吊灯原线,
        吊灯受阻=吊灯受阻, 可成交=可成交,
        回调闩锁点=回调闩锁点, 大周期翻转点=大周期翻转点,
        开关1点=开关1点, 开关2点=开关2点,
        冷静期区间=冷静期区间,
        暖机根数=w, 暖机天数=prepared.warmup_days,
        可交易日=prepared.tradable_days,
        末尾未平仓=末尾未平仓,
        参数=p, 开关=cfg, 时段模式=prepared.mode,
        丢弃段=prepared.dropped_runs,
    )


# ------------------------------------------------------------- helpers ----
def _尝试入场(
    i, D, R, 方向, 已武装, 冻结中, 回调侧, 回MA快, 回收, 开关2多, 开关2空,
    可入场, op, ATR险, X, p, cfg, 回调闩锁点, 开关1点, 开关2点,
    上次开关1, 上次开关2,
) -> "tuple[_持仓 | None, bool, bool, bool]":
    """
    三步走: 大周期方向 -> 回调闩锁 -> 两个锁齐开。

    返回 `(批 或 None, 已武装, 上次开关1, 上次开关2)` —— 状态靠返回值回写而不是闭包,
    是为了让这一段能被单独测、且没有隐藏的可变捕获。

    所有判定读的都是 `已收盘下标` 指的那一根 (即 bar i-1 及更早), 成交在 `开盘价[i]`。
    """
    if D < 0 or R < 0 or 方向 == 未定:
        return None, 已武装, 上次开关1, 上次开关2

    # --- 回调闩锁: 15m 与 2h 完全反向。看到过就记住, 不过期 ---
    if not 已武装:
        if 完全反向(回调侧[R:R + 1], 方向)[0]:
            已武装 = True
            回调闩锁点.append({"下标": i, "方向": int(方向)})
        # 回调成立的那一根**不可能**同时满足开关1 (价格重回 MA21 之上与完全反向互斥),
        # 所以这里直接返回, 不用额外的「确认根不入场」守卫。
        return None, 已武装, 上次开关1, 上次开关2

    # --- 开关1: 价格重回 MA21 之上 (空头镜像) ---
    ma = 回MA快[R]
    开关1 = False if np.isnan(ma) else (回收[R] > ma if 方向 == 多 else 回收[R] < ma)
    # --- 开关2: 水下金叉闩锁 (做多) / 水上死叉闩锁 (做空) ---
    开关2 = bool(开关2多[R] if 方向 == 多 else 开关2空[R])

    # 只记录「已武装期间」开关打开的瞬间, 否则整张图会被点淹掉
    if 开关1 and not 上次开关1:
        开关1点.append({"下标": i, "方向": int(方向)})
    if 开关2 and not 上次开关2:
        开关2点.append({"下标": i, "方向": int(方向)})
    上次开关1, 上次开关2 = 开关1, 开关2

    if not (开关1 and 开关2):
        return None, 已武装, 上次开关1, 上次开关2
    if 冻结中 or not 可入场[i]:
        # 被冷静期或闸门挡住的触发**不消耗**武装 —— 与 v3 同口径
        return None, 已武装, 上次开关1, 上次开关2
    if X < 0 or np.isnan(ATR险[X]):
        return None, 已武装, 上次开关1, 上次开关2

    入场价 = float(op[i])
    是多 = 方向 == 多
    atr0 = float(ATR险[X])
    批 = _持仓(
        方向=int(方向), 入场下标=i, 入场价=入场价, 入场ATR=atr0,
        固定止损位=固定止损(入场价, 是多, atr0, p.止损ATR倍数),
        持仓极值=入场价,
    )
    # 入场成交清空武装
    return 批, False, False, False


def _计止损(连续: int, 上次方向: int, 本次方向: int, cfg: 策略开关):
    """连续止损计数。按方向计数时, 换方向就重新从 1 开始。"""
    if cfg.冷静期_按方向计数 and 上次方向 != 0 and 本次方向 != 上次方向:
        return 1, 本次方向
    return 连续 + 1, 本次方向


def _成腿(批: _持仓, i: int, 出场价: float, 理由: str, 时刻, 交易日列, 时段号列,
         cfg: 策略开关, 跳空: bool) -> 一笔:
    return 一笔(
        方向="多" if 批.方向 == 多 else "空",
        入场下标=批.入场下标, 入场时间=pd.Timestamp(时刻[批.入场下标]),  # type: ignore[arg-type],
        入场价=批.入场价,
        出场下标=i, 出场时间=pd.Timestamp(时刻[i]),  # type: ignore[arg-type]
        出场价=float(出场价),
        理由=理由, 仓位比例=1.0,
        # bool() 而不是裸表达式: 比较结果是 np.bool_, 会让 `x.跳空成交 is True` 意外失败
        跳空成交=bool(跳空), 固定止损位=批.固定止损位,
        交易日=pd.Timestamp(交易日列[i]),  # type: ignore[arg-type]
        时段号=int(时段号列[i]),
        成本基点=cfg.成本_每笔基点,
    )


def _空结果(prepared: Prepared, p: 策略参数, cfg: 策略开关) -> 回测结果:
    return 回测结果(
        品种=prepared.symbol, 交易=[],
        权益曲线=pd.Series(dtype=float), 交易日=pd.Series(dtype="datetime64[ns]"),
        仓位=np.zeros(0, dtype=np.int8), 止损线=np.zeros(0, dtype="float64"),
        固定止损线=np.zeros(0, dtype="float64"),
        吊灯原线=np.zeros(0, dtype="float64"),
        吊灯受阻=np.zeros(0, dtype=bool), 可成交=np.zeros(0, dtype=bool),
        回调闩锁点=[], 大周期翻转点=[], 开关1点=[], 开关2点=[], 冷静期区间=[],
        暖机根数=0, 暖机天数=prepared.warmup_days, 可交易日=0, 末尾未平仓=0,
        参数=p, 开关=cfg, 时段模式=prepared.mode, 丢弃段=prepared.dropped_runs,
    )
